/**
 * USERS
 * Public profile for each auth user, created by a trigger on sign-up.
 */
create table public.users (
  id uuid references auth.users not null primary key,
  full_name text,
  avatar_url text,
  billing_address jsonb,
  payment_method jsonb
);
alter table public.users enable row level security;
create policy "Users can view own data." on public.users
  for select using (auth.uid() = id);
create policy "Users can update own data." on public.users
  for update using (auth.uid() = id);

create function public.handle_new_user()
returns trigger
language plpgsql
security definer set search_path = public
as $$
begin
  insert into public.users (id, full_name, avatar_url)
  values (
    new.id,
    new.raw_user_meta_data->>'full_name',
    new.raw_user_meta_data->>'avatar_url'
  );
  return new;
end;
$$;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute procedure public.handle_new_user();

/**
 * CUSTOMERS
 * Private mapping of user IDs to Stripe customer IDs. No policies: service role only.
 */
create table public.customers (
  id uuid references auth.users not null primary key,
  stripe_customer_id text
);
alter table public.customers enable row level security;

/**
 * PRODUCTS / PRICES
 * Synced from Stripe by webhooks. Readable by everyone.
 */
create table public.products (
  id text primary key,
  active boolean,
  name text,
  description text,
  image text,
  metadata jsonb
);
alter table public.products enable row level security;
create policy "Allow public read-only access." on public.products
  for select using (true);

create type public.pricing_type as enum ('one_time', 'recurring');
create type public.pricing_plan_interval as enum ('day', 'week', 'month', 'year');

create table public.prices (
  id text primary key,
  product_id text references public.products,
  active boolean,
  description text,
  unit_amount bigint,
  currency text check (char_length(currency) = 3),
  type public.pricing_type,
  interval public.pricing_plan_interval,
  interval_count integer,
  trial_period_days integer,
  metadata jsonb
);
alter table public.prices enable row level security;
create policy "Allow public read-only access." on public.prices
  for select using (true);

/**
 * SUBSCRIPTIONS
 * Synced from Stripe by webhooks. Users can read their own.
 */
create type public.subscription_status as enum (
  'trialing', 'active', 'canceled', 'incomplete',
  'incomplete_expired', 'past_due', 'unpaid'
);

create table public.subscriptions (
  id text primary key,
  user_id uuid references auth.users not null,
  status public.subscription_status,
  metadata jsonb,
  price_id text references public.prices,
  quantity integer,
  cancel_at_period_end boolean,
  created timestamptz default timezone('utc'::text, now()) not null,
  current_period_start timestamptz default timezone('utc'::text, now()) not null,
  current_period_end timestamptz default timezone('utc'::text, now()) not null,
  ended_at timestamptz default timezone('utc'::text, now()),
  cancel_at timestamptz default timezone('utc'::text, now()),
  canceled_at timestamptz default timezone('utc'::text, now()),
  trial_start timestamptz default timezone('utc'::text, now()),
  trial_end timestamptz default timezone('utc'::text, now())
);
alter table public.subscriptions enable row level security;
create policy "Can only view own subs data." on public.subscriptions
  for select using (auth.uid() = user_id);

/**
 * SONGS
 * Anyone can browse and search songs; only the uploader can change them.
 */
create table public.songs (
  id bigint generated by default as identity primary key,
  created_at timestamptz default now(),
  title text,
  author text,
  song_path text,
  image_path text,
  user_id uuid references auth.users on delete cascade
);
alter table public.songs enable row level security;
create policy "Songs are viewable by everyone." on public.songs
  for select using (true);
create policy "Users can insert their own songs." on public.songs
  for insert with check (auth.uid() = user_id);
create policy "Users can update their own songs." on public.songs
  for update using (auth.uid() = user_id);
create policy "Users can delete their own songs." on public.songs
  for delete using (auth.uid() = user_id);

/**
 * LIKED SONGS
 * Private to each user.
 */
create table public.liked_songs (
  user_id uuid references auth.users on delete cascade not null,
  song_id bigint references public.songs on delete cascade not null,
  created_at timestamptz default now(),
  primary key (user_id, song_id)
);
alter table public.liked_songs enable row level security;
create policy "Users can view their own likes." on public.liked_songs
  for select using (auth.uid() = user_id);
create policy "Users can like songs." on public.liked_songs
  for insert with check (auth.uid() = user_id);
create policy "Users can unlike songs." on public.liked_songs
  for delete using (auth.uid() = user_id);

/**
 * STORAGE
 * Public buckets for audio and cover art. Signed-in users upload into them;
 * only the uploader can delete their files. Images are limited to raster
 * formats: SVG can carry scripts that run when its public URL is opened.
 */
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values
  ('songs', 'songs', true, 20971520, array['audio/mpeg']),
  ('images', 'images', true, 5242880, array['image/jpeg', 'image/png', 'image/webp', 'image/gif'])
on conflict (id) do nothing;

create policy "Authenticated users can upload songs and images." on storage.objects
  for insert to authenticated
  with check (bucket_id in ('songs', 'images'));
create policy "Users can delete their own songs and images." on storage.objects
  for delete to authenticated
  using (bucket_id in ('songs', 'images') and owner = auth.uid());

