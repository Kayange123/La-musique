/**
 * PLAY HISTORY
 * One row per counted play, private to the listener. Rows are only added
 * or cleared, never edited. New table only, so this is safe to push to an
 * existing project.
 */
create table public.play_history (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid()
    references auth.users on delete cascade,
  song_id bigint not null references public.songs on delete cascade,
  played_at timestamptz not null default now()
);
-- "Recently played" reads a user's newest rows first.
create index play_history_user_played_idx
  on public.play_history (user_id, played_at desc);
-- Keeps the cascade fast when a song is deleted.
create index play_history_song_id_idx on public.play_history (song_id);

alter table public.play_history enable row level security;
create policy "Users can view their own history." on public.play_history
  for select using ((select auth.uid()) = user_id);
create policy "Users can add to their own history." on public.play_history
  for insert with check ((select auth.uid()) = user_id);
create policy "Users can clear their own history." on public.play_history
  for delete using ((select auth.uid()) = user_id);
