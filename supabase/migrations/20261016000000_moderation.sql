/**
 * MODERATION
 * Listeners report songs; admins hide them. A hidden song disappears for
 * everyone except its uploader and admins, everywhere songs are read
 * (lists, likes, playlists, history), because the songs select policy
 * itself hides it. Uploaders can't un-hide their own songs: hiding and
 * restoring only happen through moderate_song(), which checks is_admin().
 *
 * Additive apart from two changes to songs: the select policy is
 * replaced, and update is narrowed to title and author (the only columns
 * the app edits).
 */

/**
 * ADMINS
 * Granted by hand with SQL (see the README). No policies and no grants:
 * the table is only read through is_admin().
 */
create table public.admins (
  user_id uuid primary key references auth.users on delete cascade,
  created_at timestamptz not null default now()
);
alter table public.admins enable row level security;
revoke all on public.admins from anon, authenticated;

-- Security definer so it can read admins whatever the caller's rights.
-- Anon needs it too: the songs select policy calls it for every visitor.
create function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.admins where user_id = (select auth.uid())
  );
$$;
revoke execute on function public.is_admin() from public;
grant execute on function public.is_admin() to anon, authenticated;

/**
 * HIDDEN SONGS
 */
alter table public.songs
  add column hidden_at timestamptz;

-- Replaces the old "viewable by everyone" policy. Both can't coexist:
-- permissive policies are OR'd, so the old one would show everything.
drop policy "Songs are viewable by everyone." on public.songs;
create policy "Visible songs are viewable by everyone." on public.songs
  for select using (
    hidden_at is null
    or user_id = (select auth.uid())
    or (select public.is_admin())
  );

-- Uploaders edit the title and artist only. Without this, the owner's
-- update policy would let them clear hidden_at (or repoint song_path).
revoke update on public.songs from anon, authenticated;
grant update (title, author) on public.songs to authenticated;

/**
 * REPORTS
 * One per listener per song. Reporters see their own reports; admins see
 * all. Uploaders never see who reported them.
 */
create table public.song_reports (
  id bigint generated by default as identity primary key,
  song_id bigint not null references public.songs on delete cascade,
  reporter_id uuid not null default auth.uid()
    references auth.users on delete cascade,
  reason text not null
    check (reason in ('copyright', 'abuse', 'spam', 'other')),
  details text check (details is null or char_length(details) <= 500),
  created_at timestamptz not null default now(),
  resolved_at timestamptz,
  resolved_by uuid references auth.users on delete set null,
  unique (song_id, reporter_id)
);
alter table public.song_reports enable row level security;

create policy "Users can report songs they can see." on public.song_reports
  for insert with check (
    reporter_id = (select auth.uid())
    -- Runs under the reporter's RLS, so hidden songs can't be reported.
    and exists (select 1 from public.songs s where s.id = song_id)
  );
create policy "Users can view their own reports; admins all."
  on public.song_reports for select using (
    reporter_id = (select auth.uid()) or (select public.is_admin())
  );

-- Reporters choose the song, reason and details; nothing else. Resolving
-- goes through moderate_song().
revoke insert, update, delete on public.song_reports from anon, authenticated;
grant insert (song_id, reason, details) on public.song_reports to authenticated;

-- The admin queue reads open reports per song.
create index song_reports_open_idx
  on public.song_reports (song_id) where resolved_at is null;

/**
 * moderate_song(song_id, action)
 *   'hide'    hide the song and resolve its open reports
 *   'dismiss' resolve its open reports, leaving the song visible
 *   'restore' make a hidden song visible again
 * Admins only. Security definer, so it checks is_admin() itself.
 */
create function public.moderate_song(target bigint, action text)
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  if not public.is_admin() then
    raise exception 'Only admins can moderate songs'
      using errcode = '42501';
  end if;
  if action not in ('hide', 'dismiss', 'restore') then
    raise exception 'Unknown moderation action: %', action
      using errcode = '22023';
  end if;

  if action = 'hide' then
    update public.songs set hidden_at = now()
    where id = target and hidden_at is null;
  elsif action = 'restore' then
    update public.songs set hidden_at = null where id = target;
  end if;

  if action in ('hide', 'dismiss') then
    update public.song_reports
    set resolved_at = now(), resolved_by = (select auth.uid())
    where song_id = target and resolved_at is null;
  end if;
end;
$$;
revoke execute on function public.moderate_song(bigint, text) from public, anon;
grant execute on function public.moderate_song(bigint, text) to authenticated;
