/**
 * PLAYLISTS
 * Named lists of songs, private to their owner. New tables only, so this
 * is safe to push to an existing project.
 */
create table public.playlists (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid()
    references auth.users on delete cascade,
  name text not null check (char_length(btrim(name)) between 1 and 100),
  created_at timestamptz not null default now()
);
create index playlists_user_id_idx on public.playlists (user_id);

alter table public.playlists enable row level security;
create policy "Users can view their own playlists." on public.playlists
  for select using ((select auth.uid()) = user_id);
create policy "Users can create their own playlists." on public.playlists
  for insert with check ((select auth.uid()) = user_id);
create policy "Users can rename their own playlists." on public.playlists
  for update using ((select auth.uid()) = user_id)
  with check ((select auth.uid()) = user_id);
create policy "Users can delete their own playlists." on public.playlists
  for delete using ((select auth.uid()) = user_id);

/**
 * PLAYLIST SONGS
 * Which songs are in which playlist. Removing a playlist or a song removes
 * its rows here. Access follows the parent playlist's owner; there's no
 * update policy because rows are only ever added or removed.
 */
create table public.playlist_songs (
  playlist_id bigint not null
    references public.playlists on delete cascade,
  song_id bigint not null references public.songs on delete cascade,
  added_at timestamptz not null default now(),
  primary key (playlist_id, song_id)
);
-- Keeps the cascade fast when a song is deleted.
create index playlist_songs_song_id_idx on public.playlist_songs (song_id);

alter table public.playlist_songs enable row level security;
create policy "Users can view songs in their own playlists."
  on public.playlist_songs for select using (
    exists (
      select 1 from public.playlists p
      where p.id = playlist_id and p.user_id = (select auth.uid())
    )
  );
create policy "Users can add songs to their own playlists."
  on public.playlist_songs for insert with check (
    exists (
      select 1 from public.playlists p
      where p.id = playlist_id and p.user_id = (select auth.uid())
    )
  );
create policy "Users can remove songs from their own playlists."
  on public.playlist_songs for delete using (
    exists (
      select 1 from public.playlists p
      where p.id = playlist_id and p.user_id = (select auth.uid())
    )
  );
